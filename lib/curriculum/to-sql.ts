/**
 * Generates supabase/seed/seed.sql from the TypeScript curriculum (the source of truth).
 * Run: pnpm tsx lib/curriculum/to-sql.ts
 * Idempotent SQL: every insert is `on conflict ... do update`.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { curriculum } from "./index";
import { validateCurriculum } from "./validate";

function lit(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}
function textArray(values: string[]): string {
  if (values.length === 0) return "'{}'::text[]";
  return `array[${values.map(lit).join(", ")}]::text[]`;
}
function jsonb(value: unknown): string {
  // Escape single quotes for SQL; JSON itself never needs backslash-doubling in standard_conforming_strings mode.
  return `${lit(JSON.stringify(value))}::jsonb`;
}

export function curriculumToSql(): string {
  const { path, modules, skills } = curriculum;
  const lines: string[] = [];
  lines.push("-- GENERATED by lib/curriculum/to-sql.ts from lib/curriculum/** — do not edit by hand.");
  lines.push(`-- Path: ${path.id} | ${skills.length} skills | ${modules.length} modules | generated ${new Date().toISOString()}`);
  lines.push("begin;");
  lines.push("");

  lines.push("-- learning_paths");
  lines.push(
    `insert into public.learning_paths (id, title, description, difficulty, published) values (${lit(path.id)}, ${lit(path.title)}, ${lit(path.description)}, ${path.difficulty}, ${path.published})`,
  );
  lines.push("  on conflict (id) do update set title = excluded.title, description = excluded.description, difficulty = excluded.difficulty, published = excluded.published;");
  lines.push("");

  // Module (parent) skills first so leaf rows can reference them.
  lines.push("-- skills: module parents");
  for (const m of modules) {
    lines.push(
      `insert into public.skills (id, name, description, category, difficulty, parent_skill_id, prerequisite_skill_ids) values (${lit(m.id)}, ${lit(m.title)}, ${lit(m.summary)}, ${lit(m.id)}, ${moduleDifficulty(m.id)}, null, ${textArray(m.prerequisiteModuleIds)})`,
    );
    lines.push("  on conflict (id) do update set name = excluded.name, description = excluded.description, category = excluded.category, difficulty = excluded.difficulty, parent_skill_id = excluded.parent_skill_id, prerequisite_skill_ids = excluded.prerequisite_skill_ids;");
  }
  lines.push("");

  lines.push("-- skills: leaves");
  for (const s of skills) {
    lines.push(
      `insert into public.skills (id, name, description, category, difficulty, parent_skill_id, prerequisite_skill_ids) values (${lit(s.id)}, ${lit(s.name)}, ${lit(s.description)}, ${lit(s.category)}, ${s.difficulty}, ${s.parentSkillId ? lit(s.parentSkillId) : "null"}, ${textArray(s.prerequisiteSkillIds)})`,
    );
    lines.push("  on conflict (id) do update set name = excluded.name, description = excluded.description, category = excluded.category, difficulty = excluded.difficulty, parent_skill_id = excluded.parent_skill_id, prerequisite_skill_ids = excluded.prerequisite_skill_ids;");
  }
  lines.push("");

  lines.push("-- learning_path_skills (sequence follows module order, then skill order within the module)");
  let seq = 0;
  for (const m of modules) {
    for (const sid of m.skillIds) {
      seq += 1;
      const skill = skills.find((s) => s.id === sid)!;
      lines.push(
        `insert into public.learning_path_skills (learning_path_id, skill_id, sequence, prerequisite_skill_ids) values (${lit(path.id)}, ${lit(sid)}, ${seq}, ${textArray(skill.prerequisiteSkillIds)})`,
      );
      lines.push("  on conflict (learning_path_id, skill_id) do update set sequence = excluded.sequence, prerequisite_skill_ids = excluded.prerequisite_skill_ids;");
    }
  }
  lines.push("");

  lines.push("-- modules (content = lib/types/curriculum.ts Module as JSON)");
  for (const m of modules) {
    lines.push(
      `insert into public.modules (id, learning_path_id, sequence, content) values (${lit(m.id)}, ${lit(path.id)}, ${m.sequence}, ${jsonb(m)})`,
    );
    lines.push("  on conflict (id) do update set learning_path_id = excluded.learning_path_id, sequence = excluded.sequence, content = excluded.content;");
  }
  lines.push("");
  lines.push("commit;");
  lines.push("");
  return lines.join("\n");
}

/** Module-level difficulty used for the parent skill row: the max of its leaf skills. */
function moduleDifficulty(moduleId: string): number {
  const leaves = curriculum.skills.filter((s) => s.parentSkillId === moduleId);
  return leaves.reduce((max, s) => Math.max(max, s.difficulty), 1);
}

const isDirectRun =
  typeof process !== "undefined" &&
  Array.isArray(process.argv) &&
  /to-sql\.ts$/.test(process.argv[1] ?? "");

if (isDirectRun) {
  const errors = validateCurriculum();
  if (errors.length) {
    console.error(`Refusing to generate SQL: curriculum has ${errors.length} validation problems. Run validate.ts.`);
    process.exit(1);
  }
  const out = resolve(process.cwd(), "supabase/seed/seed.sql");
  mkdirSync(dirname(out), { recursive: true });
  const sql = curriculumToSql();
  writeFileSync(out, sql, "utf8");
  console.log(`Wrote ${out} (${sql.length.toLocaleString()} chars)`);
}
